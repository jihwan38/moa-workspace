#!/usr/bin/env python3
"""Two QKV cancellation diagnostics using frozen original reference functions."""
import argparse
import hashlib
import json
import sys
from pathlib import Path
import numpy as np
import torch
from safetensors.numpy import save_file

H, QS, PS, DS, TS, E = 3840, 4096, 2048, 256, 1024, 32768
NAMES = ["tiny_lost_after_pre_rms", "larger_tiny_preserved_control"]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def raw_bf(t):
    return t.to(torch.bfloat16).contiguous().view(torch.uint8).numpy().reshape(-1).copy()


def weight_codes(rows):
    row = np.where(np.arange(H) % 480 < 2, 0x38, 0x77).astype(np.uint8)
    return np.broadcast_to(row, (rows, H)).copy()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--official-scripts", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    sys.path.insert(0, str(args.official_scripts.resolve()))
    import generate_references as official
    from fixture_prng import checksum
    torch.set_num_threads(4)
    torch.set_grad_enabled(False)
    torch.use_deterministic_algorithms(True)
    args.out.mkdir(parents=True, exist_ok=True)
    pos = official._run_pos(0)
    assert pos == 1763
    cos_raw, sin_raw = official.rope_tables(DS, 10000.0, 1.0, pos)
    cos = torch.from_numpy(cos_raw).to(torch.bfloat16).view(1, 1, DS)
    sin = torch.from_numpy(sin_raw).to(torch.bfloat16).view(1, 1, DS)
    tensors, records = {}, []
    for case, name in enumerate(NAMES):
        x = torch.full((H,), 2.0**(-23 if case == 0 else -12), dtype=torch.bfloat16)
        x[0::480], x[1::480] = 1, -1
        gamma = torch.ones(H, dtype=torch.bfloat16)
        h = official.rms_norm(H, gamma)(x)
        arrays = {"x": raw_bf(x), "input_rms_weight": raw_bf(gamma),
                  "q_rms_weight": raw_bf(torch.ones(DS)), "k_rms_weight": raw_bf(torch.ones(DS)),
                  "cos_row": raw_bf(cos.reshape(-1)),
                  "sin_row": raw_bf(torch.from_numpy(official.negate_low_half(sin_raw))),
                  "rope_offset": np.array([pos*DS*2], dtype="<i4").view(np.uint8),
                  "kv_offset": np.array([(pos % TS)*PS*2], dtype="<i4").view(np.uint8)}
        mids = {"x": x.float(), "pre_rms_mean_square": x.float().square().mean(),
                "pre_rms_inverse": torch.rsqrt(x.float().square().mean()+official.EPS),
                "pre_rms_bf16": h.float()}
        expected = {}
        for key, rows in [("q", QS), ("k", PS), ("v", PS)]:
            codes = weight_codes(rows)
            weights = torch.from_numpy(codes).view(torch.float8_e4m3fn).float()
            scale = torch.full((rows,), 2.0**-10, dtype=torch.bfloat16)
            raw = h.float() @ weights.T
            projected = official.scaled_projection(h, weights, scale).view(rows//DS, DS)
            normed = official.rms_norm(DS, None if key == "v" else torch.ones(DS, dtype=torch.bfloat16))(projected)
            out = normed if key == "v" else official.apply_rotary_pos_emb(
                normed.view(1, 1, rows//DS, DS), cos, sin, unsqueeze_dim=2)
            expected[key] = out.reshape(-1)
            mids.update({f"{key}.raw": raw, f"{key}.scaled_f32": raw*scale.float(),
                         f"{key}.projected": projected.float(),
                         f"{key}.mean_square": projected.float().square().mean(-1),
                         f"{key}.inverse_rms": torch.rsqrt(projected.float().square().mean(-1)+official.EPS),
                         f"{key}.normalized": normed.float(), f"{key}.expected": out.float()})
            arrays[key+"_weight"] = codes.reshape(-1)
            arrays[key+"_weight_scale"] = raw_bf(scale)
            tensors[f"case{case}.expected.{key}"] = out.float().reshape(-1).numpy().copy()
        assert bool((expected["v"] == (0.85546875 if case == 0 else 1.0)).all())
        assert all(bool(torch.isfinite(t).all()) for t in mids.values())
        # Full HBM inputs are independently regenerated by Rust. Store only their
        # row/constant descriptions, but hash and checksum the actual full bytes.
        for key in ("cos", "sin"):
            full = np.zeros(E*DS*2, dtype=np.uint8)
            full[pos*DS*2:(pos+1)*DS*2] = arrays[key+"_row"]
            arrays[key] = full
        for key, count, bits in [("k_cache_init", TS*PS, 0x3e80),
                                 ("v_cache_init", TS*PS, 0xbf00),
                                 ("q_out_init", QS, 0x3fc0)]:
            arrays[key] = np.full(count, bits, dtype="<u2").view(np.uint8)
        hashes, checks = {}, {}
        generated = {"q_weight", "k_weight", "v_weight", "cos", "sin",
                     "k_cache_init", "v_cache_init", "q_out_init"}
        for key, array in arrays.items():
            hashes[key], checks[key] = sha(array.tobytes()), int(checksum(array))
            tensors[f"case{case}.checksum.{key}"] = np.array([checks[key]], dtype=np.int64)
            if key not in generated:
                tensors[f"case{case}.input.{key}"] = array
        records.append({"case": case, "name": name, "input_small_power": -23 if case == 0 else -12,
                        "official_qkv_x_generator_support": False, "finite_intermediates": True,
                        "sha256": hashes, "checksums": checks,
                        "ranges": {k: {"min": float(v.min()), "max": float(v.max())} for k,v in mids.items()},
                        "first_output_bf16_bits": {k: [f"{n:04x}" for n in v.view(torch.uint16)[:8].tolist()] for k,v in expected.items()}})
        print(json.dumps({"case":case,"finite":True,"v_expected":float(expected["v"][0]),"checks":len(checks)}), flush=True)
    fixture = args.out / "boundary.safetensors"
    save_file(tensors, str(fixture), metadata={"purpose":"QKV-only diagnostic, not official input distribution or performance"})
    meta = {"cases":2,"atol":.04,"rtol":.01,"pos":pos,"slot":pos % TS,"torch":torch.__version__,
            "cpu_threads":4,"oracle":"original rms_norm, scaled_projection, apply_rotary_pos_emb",
            "official_sources": {str(p.relative_to(args.official_scripts)): sha(p.read_bytes()) for p in
                 [args.official_scripts/"generate_references.py",args.official_scripts/"reference/gemma4.py",args.official_scripts/"fixture_prng.py"]},
            "payload":{"bytes":fixture.stat().st_size,"sha256":sha(fixture.read_bytes())},"records":records}
    (args.out/"cpu-references.json").write_text(json.dumps(meta,indent=2)+"\n")


if __name__ == "__main__":
    main()
