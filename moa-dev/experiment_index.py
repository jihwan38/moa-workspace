#!/usr/bin/env python3
"""Render the optimization index from curated decisions and original measurements.

This reads local evidence only; it never builds, submits, or changes a kernel.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import statistics
import subprocess

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs/experiments/catalog.json"
BASELINE = ROOT / "baseline/current.json"
RESULTS = ROOT / "docs/experiments/optimization-results.md"
METHODS = ROOT / "baseline/methods.md"
KERNELS = {
    "QKV": "sliding_project_qkv",
    "O": "sliding_attention_output",
    "FFN": "decoder_feedforward",
}
CATEGORIES = {
    "improved": "빨라진 기록",
    "inconclusive": "차이가 작거나 반복에서 이득을 확인하지 못함",
    "regressed": "느리게 측정됨",
    "accuracy_limited": "빨랐지만 후속 정확도 검사에서 제한 확인",
    "correctness_fix": "속도 비용을 감수한 정확도 수정",
    "invalid": "정확도 실패·실행 실패",
    "control": "대조군·기존 커널 조합",
    "static_only": "컴파일·정적 분석만 수행",
}


def read_json(path):
    return json.loads((ROOT / path).read_text())


def link(path, label, output):
    assert (ROOT / path).is_file(), path
    return f"[{label}]({os.path.relpath(ROOT / path, output.parent)})"


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def measurement(path, kernel):
    """Use only a complete valid package; recompute the job-median aggregate."""
    report = read_json(path)
    assert report["valid"] is True, path
    runs = report["runs"]
    assert runs and all(run["valid"] is True for run in runs), path
    ids = [run["job"]["id"] for run in runs]
    assert len(ids) == len(set(ids)), path
    assert all(run["package_files"] == runs[0]["package_files"] for run in runs), path
    values = [run["kernels"][KERNELS[kernel]]["median_cycles"] for run in runs]
    median = statistics.median(values)
    assert median == report["aggregate"][KERNELS[kernel]]["median_cycles"], path
    return median, ids


def check_comparable(candidate, reference):
    left_run = read_json(candidate)["runs"][0]
    right_run = read_json(reference)["runs"][0]
    left = left_run["package_files"]
    right = right_run["package_files"]
    for name in ("fixtures.safetensors", "remote_entrypoint.sh"):
        left_name = left_run.get("benchmark_files", {}).get(name, name)
        right_name = right_run.get("benchmark_files", {}).get(name, name)
        assert left[left_name] == right[right_name], f"Different {name}: {candidate} vs {reference}"


def validate_baseline(baseline, check_live):
    revision = baseline["git"]["commit"]
    tag_commit = subprocess.check_output(
        ["git", "rev-parse", baseline["git"]["tag"] + "^{commit}"], cwd=ROOT, text=True
    ).strip()
    assert tag_commit == revision, "Baseline tag no longer resolves to its recorded commit"
    frozen = read_json(baseline["compile_inputs"])
    crate = "furiosa-opt-gemma4-12B"
    if check_live:
        expected = {name for name in frozen if name.startswith("src/")}
        actual = {p.relative_to(ROOT / crate).as_posix()
                  for p in (ROOT / crate / "src").rglob("*") if p.is_file()}
        assert actual == expected, "Current source file inventory differs from the baseline"
    for name, info in frozen.items():
        path = f"{crate}/{name}" if name != "Cargo.lock" else baseline["tracked_lock"]
        content = subprocess.check_output(["git", "show", f"{revision}:{path}"], cwd=ROOT)
        assert hashlib.sha256(content).hexdigest() == info["sha256"], path
        if check_live:
            live_path = ROOT / crate / name
            assert hashlib.sha256(live_path.read_bytes()).hexdigest() == info["sha256"], str(live_path)
    for path in [baseline["source_build_audit"], baseline["recent_control_report"],
                 *baseline["correctness_evidence"]]:
        assert (ROOT / path).is_file(), path
    methods = baseline["methods"]
    ids = {method["id"] for method in methods}
    assert len(ids) == len(methods), "Duplicate method ID"
    for method in methods:
        assert set(method["coupled_with"]) <= ids, method["id"]
        for source in method["implementation"]:
            content = subprocess.check_output(
                ["git", "show", f"{revision}:{source['path']}"], cwd=ROOT, text=True
            )
            for symbol in source["symbols"]:
                assert re.search(r"\b" + re.escape(symbol) + r"\b", content), symbol
        for path in method["evidence"]:
            assert (ROOT / path).is_file(), path
    for kernel in KERNELS:
        measurement(baseline["performance_report"], kernel)


def render_methods(baseline):
    lines = [
        f"# {baseline['id']}에 적용된 방법", "",
        "<!-- Generated by moa-dev/experiment_index.py; edit the recipe named in baseline/current.json. -->", "",
        "[Baseline 개요](README.md) · " + link(read_json(BASELINE)["recipe"], "원본 구성표", METHODS)
        + " · [성능별 실험 분류](../docs/experiments/optimization-results.md)", "",
        "아래 ID는 **현재 구현의 구성요소를 기록하는 이름**이다. 독립적인 런타임 스위치나 "
        "개별 속도 향상률을 뜻하지 않는다. `함께 확인`은 현재 배치·자료형·호출 계약이 "
        "연결된 항목이며, 새 구현에서 이 의존성을 해소할 수 있다.", "",
        f"코드 기준: `{baseline['git']['tag']}` / `{baseline['git']['commit']}`. "
        "소스 링크는 작업 트리를 가리킨다. 이후 변경됐으면 위 commit의 같은 파일을 확인한다.", "",
    ]
    for method in baseline["methods"]:
        lines += [f"## {method['id']} — {method['name']}", "", method["behavior"], ""]
        lines += [f"- 적용 커널: {', '.join(method['kernels'])}",
                  f"- 현재 설정: {method['parameters']}",
                  f"- 함께 확인: {', '.join(method['coupled_with']) or '없음'}",
                  f"- 변경 시 유지할 조건: {method['invariant']}"]
        sources = [link(source["path"], Path(source["path"]).name, METHODS)
                   + " — " + ", ".join(f"`{s}`" for s in source["symbols"])
                   for source in method["implementation"]]
        lines += ["- 코드: " + "; ".join(sources),
                  "- 근거: " + ", ".join(link(p, Path(p).name, METHODS) for p in method["evidence"]), ""]
    return "\n".join(lines)


def render_results(catalog, baseline):
    entries = catalog["entries"]
    assert len({e["id"] for e in entries}) == len(entries), "Duplicate catalog ID"
    assert all(e["category"] in CATEGORIES for e in entries)
    lines = [
        "# 최적화 방법별 결과", "",
        "<!-- Generated by moa-dev/experiment_index.py; edit catalog.json. -->", "",
        f"현재 채택본은 **{baseline['id']}**다. [현재 적용 방법](../../baseline/README.md) · "
        "[시간순 원장](README.md) · [조합 실험 작성 양식](combination-template.md)", "",
        "수치는 원본 Arena 결과 JSON에서 읽는다. 각 행은 **변경 대상 커널**에 대한 비교이며, "
        "변경하지 않은 다른 커널의 흔들림을 최적화 효과로 세지 않는다. 같은 E 번호가 "
        "다른 커널에서 서로 다른 판정을 받을 수 있다.", "",
        "- 변화율 = `(후보 cycles / 기준 cycles − 1) × 100`. **음수는 빨라짐, 양수는 느려짐**이다.",
        "- 측정 수는 `기준 job 수 → 후보 job 수`. 한 job 안의 공식 입력 3개 중앙값을 사용하며, "
        "여러 job이면 그 중앙값들의 중앙값을 사용한다. 실패 행은 후보 job 수만 표시한다. "
        "1회만 실행한 결과로 실행 간 변동을 알 수 없다.",
        "- 비교 기준은 개선율을 계산하는 대조 기록이다. 패치의 소스 부모나 한 가지 변화만 있는 "
        "대조 실험이라는 뜻은 아니다. 이전 조합의 기록에는 여러 변화가 함께 들어 있다.",
        "- 분류는 원장·반복·정확도 근거를 확인한 판단이다. 임의의 ±1% 문턱으로 자동 판정하지 않는다. "
        "과거 채택·성능 관측과 **현재 채택**을 구별한다.",
        "- 컴파일 예상 cycles, 추가 입력 진단 cycles, 정확도 실패 패키지의 cycles는 성능표에 섞지 않는다. "
        "이 표는 공식 점수·순위 또는 모델 전체 처리량이 아니다.", "",
        f"수록: {len(entries)}개 커널별 비교/진단 항목. {catalog['coverage']}", "",
        "E59처럼 작은 감소가 실행 변동과 겹치거나 E50처럼 후속 반복에서 재현되지 않으면 "
        "미확인으로 남긴다. E38/E39처럼 자체 실험 계열의 이전 후보보다 빨라져도 "
        "채택본보다 느린 경우에는 그 비교를 함께 적는다.", "",
    ]
    lines += ["| 분류 | 항목 수 |", "|---|---:|"]
    for category, title in CATEGORIES.items():
        count = sum(entry["category"] == category for entry in entries)
        if count:
            lines.append(f"| [{title}](#{category}) | {count} |")
    lines.append("")
    for category, title in CATEGORIES.items():
        group = [e for e in entries if e["category"] == category]
        if not group:
            continue
        lines += [f'<a id="{category}"></a>', "", f"## {title}", "",
                  "| 실험·방법 | 대상 | 비교 기준 → 후보 cycles | 변화 | job 수 | 판정·후속 근거 |",
                  "|---|---|---|---:|---:|---|"]
        for entry in group:
            report_path = entry.get("report")
            label = f"{entry['id']} · {entry['method']}"
            label = link(report_path, label, RESULTS) if report_path else label
            comparison, change, count = "—", "—", "—"
            if category not in {"invalid", "static_only"}:
                candidate, jobs = measurement(report_path, entry["kernel"])
                control, control_jobs = measurement(entry["reference"], entry["kernel"])
                check_comparable(report_path, entry["reference"])
                reference = link(entry["reference"], entry["reference_label"], RESULTS)
                comparison = f"{reference}: {control:,.0f} → {candidate:,.0f}"
                change = f"{(candidate / control - 1) * 100:+.2f}%"
                count = f"{len(control_jobs)} → {len(jobs)}"
            elif category == "invalid":
                report = read_json(report_path)
                assert report["valid"] is False, report_path
                count = str(len(report["runs"]))
                comparison = "성능 집계 제외"
            else:
                assert report_path is None, entry["id"]
                comparison, count = "Arena 미측정", "0"
            note = entry["note"]
            if entry.get("evidence"):
                note += " " + ", ".join(link(p, f"근거{i + 1}", RESULTS)
                                         for i, p in enumerate(entry["evidence"]))
            lines.append("| " + " | ".join(map(cell, [label, entry["kernel"], comparison, change, count, note])) + " |")
        lines.append("")
    lines += ["## 기록 추가", "",
              "새 측정 JSON은 기존 collector로 보존한 뒤 [catalog.json](catalog.json)에 변경 대상, "
              "비교 기준, 분류와 이유를 추가한다. 이 문서의 수치는 직접 고치지 않는다. "
              "정확도·컴파일 실패도 같은 ID의 근거를 남긴다.", "",
              "```bash", "python3 moa-dev/experiment_index.py",
              "python3 moa-dev/experiment_index.py --check", "```", "",
              "명령은 저장소 루트에서 실행한다. 소스·실험 결과를 읽고 두 안내 문서만 생성한다. "
              "NPU 실행이나 제출은 하지 않는다.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated documents are stale")
    parser.add_argument("--check-live", action="store_true", help="Also require current compile inputs to equal the baseline")
    args = parser.parse_args()
    baseline = read_json(read_json(BASELINE)["recipe"])
    validate_baseline(baseline, args.check_live)
    outputs = {METHODS: render_methods(baseline), RESULTS: render_results(read_json(CATALOG), baseline)}
    for path, content in outputs.items():
        if args.check:
            assert path.read_text() == content, f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.write_text(content)
    print(f"Validated {baseline['id']} inputs, method references and measurements; {'checked' if args.check else 'wrote'} {len(outputs)} documents.")


if __name__ == "__main__":
    main()
